m  = Container()
I  = Set(m, "I",  records=PRODUCTS, description="produtos")
J  = Set(m, "J",  records=[str(j) for j in range(1, NUM_PROCESSES+1)], description="processos")
T  = Set(m, "T",  records=[str(t) for t in range(1, NUM_PERIODS+1)],   description="periodos")
TL = Alias(m, "TL", alias_with=T)
A  = Parameter(m, "A", domain=[I,J], records=pd.DataFrame(A_RECORDS, columns=["i","j","value"]),
               description="t/dia do item i usando processo j")
D  = Parameter(m, "D", domain=[I,T], records=pd.DataFrame(D_RECORDS, columns=["i","t","value"]),
               description="demanda do produto i no periodo t")
X  = Variable(m, "X", type="binary",   domain=[J,T], description="processo j no periodo t")
E  = Variable(m, "E", type="positive", domain=[I,T], description="excesso")
F  = Variable(m, "F", type="positive", domain=[I,T], description="falta")
Z  = Variable(m, "Z", description="objetivo")
EQ_OBJ  = Equation(m, "EQ_OBJ",  description="funcao objetivo")
EQ_DEM  = Equation(m, "EQ_DEM",  domain=[I,T], description="demanda acumulada")
EQ_PROP = Equation(m, "EQ_PROP", domain=[T],   description="max 1 processo/periodo")
i, j, t, tl = I, J, T, TL
EQ_OBJ[...]  = Z == Sum([i,t], F[i,t] + 0.001*E[i,t])
EQ_DEM[i,t]  = (Sum([j,tl], (A[i,j]*X[j,tl]).where[Ord(tl) <= Ord(t)])
                + F[i,t] - E[i,t]
                == Sum(tl, D[i,tl].where[Ord(tl) <= Ord(t)]))
EQ_PROP[t]   = Sum(j, X[j,t]) <= 1
ALCOA = Model(m, "ALCOA", equations=m.getEquations(), problem="MIP", sense="MIN", objective=Z)

